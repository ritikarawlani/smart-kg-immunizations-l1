#!/usr/bin/env node
// graph/immunizations-l1.json -> graph/immunizations-l1.cypher, for Neo4j.
//
// Instances only. Load smart-kg's ontology/l1/l1.cypher first if you want the type graph beside
// them: each instance node is linked to its :KGClass by INSTANCE_OF, so the two meet in one store.
//
//   cypher-shell -d neo4j -f ../smart-kg/ontology/l1/l1.cypher
//   cypher-shell -d neo4j -f graph/immunizations-l1.cypher
//
// Node labels are :L1 plus the class in PascalCase; `id` is the IRI. Relationship types are the
// ontology's predicates. Properties that are lists of scalars stay lists; anything nested is
// stored as a JSON string, because Neo4j properties cannot nest. Every statement is MERGE.

import { readFileSync, writeFileSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const doc = JSON.parse(readFileSync(join(ROOT, "graph", "immunizations-l1.json"), "utf8"));

const pascal = (s) => s.split("-").map((w) => w[0].toUpperCase() + w.slice(1)).join("");
const str = (s) => `'${String(s).replace(/\\/g, "\\\\").replace(/'/g, "\\'").replace(/\n/g, "\\n")}'`;
const val = (v) => {
  if (v === null || v === undefined) return "null";
  if (typeof v === "number" || typeof v === "boolean") return String(v);
  if (Array.isArray(v) && v.every((x) => x !== null && typeof x !== "object")) return `[${v.map(val).join(", ")}]`;
  if (typeof v === "object") return str(JSON.stringify(v));
  return str(v);
};
const map = (o) => `{${Object.entries(o).filter(([, v]) => v !== undefined).map(([k, v]) => `\`${k}\`: ${val(v)}`).join(", ")}}`;

const out = [
  "// L1 instance graph for the WHO immunization DAK's section 1.2 sources.",
  "// Generated by tools/to-cypher.mjs from graph/immunizations-l1.json. Do not edit.",
  "// Run against a user database (:use neo4j), not `system`.",
  "",
  "CREATE CONSTRAINT l1_id IF NOT EXISTS FOR (n:L1) REQUIRE n.id IS UNIQUE;",
  "",
];
for (const n of doc.nodes) {
  const props = { label: n.label, derivation: n.derivation, note: n.note, flagRef: n.flagRef,
                  evidence: n.evidence, ...n.properties };
  out.push(`MERGE (n:L1:${pascal(n.type)} {id: ${str(n.id)}}) SET n += ${map(props)};`);
}
out.push("");
for (const e of doc.edges) {
  const props = { qualifier: e.qualifier, derivation: e.derivation, note: e.note, evidence: e.evidence, ...(e.properties ?? {}) };
  out.push(`MATCH (a:L1 {id: ${str(e.source)}}), (b:L1 {id: ${str(e.target)}}) ` +
           `MERGE (a)-[r:${e.predicate}${e.qualifier ? ` {qualifier: ${str(e.qualifier)}}` : ""}]->(b) SET r += ${map(props)};`);
}
out.push("");
out.push("// Join to the type graph, where smart-kg's ontology/l1/l1.cypher has been loaded.");
for (const t of [...new Set(doc.nodes.map((n) => n.type))]) {
  out.push(`MATCH (n:L1:${pascal(t)}), (c:KGClass {id: ${str(t)}}) MERGE (n)-[:INSTANCE_OF]->(c);`);
}
writeFileSync(join(ROOT, "graph", "immunizations-l1.cypher"), out.join("\n") + "\n");
console.log(`${doc.nodes.length} nodes, ${doc.edges.length} edges -> graph/immunizations-l1.cypher`);
